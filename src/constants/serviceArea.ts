/**
 * Inverted mask paths for Google Maps.
 * Outer ring encompasses world bounds.
 * Inner hole is the exact Tacurong City polygon.
 * When drawn as a google.maps.Polygon, areas outside Tacurong are dimmed at 35% opacity.
 */
export const TACURONG_MASK_PATHS: Array<Array<{ lat: number; lng: number }>> = [
  [
    { lat: 85, lng: -180 },
    { lat: 85, lng: 180 },
    { lat: -85, lng: 180 },
    { lat: -85, lng: -180 },
    { lat: 85, lng: -180 },
  ],
  TACURONG_POLYGON_COORDINATES,
];

/**
 * Standard ray-casting Point-in-Polygon (PIP) test.
 */
export function isPointInPolygon(
  lat: number,
  lng: number,
  polygon: Array<{ lat: number; lng: number }>
): boolean {
  const y = Number(lat);
  const x = Number(lng);
  if (!Number.isFinite(y) || !Number.isFinite(x)) return false;

  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const xi = polygon[i].lng;
    const yi = polygon[i].lat;
    const xj = polygon[j].lng;
    const yj = polygon[j].lat;
    const straddles = yi > y !== yj > y;
    if (straddles && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

/**
 * Distance in kilometers from (lat, lng) to the nearest edge of the Tacurong polygon.
 * Returns 0 if the point is inside the polygon. Returns Infinity if coordinates are non-finite.
 */
export function distanceOutsideTacurongKm(lat: number, lng: number): number {
  const y = Number(lat);
  const x = Number(lng);
  if (!Number.isFinite(y) || !Number.isFinite(x)) return Infinity;

  if (isPointInPolygon(y, x, TACURONG_POLYGON_COORDINATES)) return 0;

  const kmPerDegLat = 111.195;
  const kmPerDegLng = kmPerDegLat * Math.cos((y * Math.PI) / 180);
  let nearest = Infinity;

  const poly = TACURONG_POLYGON_COORDINATES;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const ax = (poly[j].lng - x) * kmPerDegLng;
    const ay = (poly[j].lat - y) * kmPerDegLat;
    const bx = (poly[i].lng - x) * kmPerDegLng;
    const by = (poly[i].lat - y) * kmPerDegLat;
    const dx = bx - ax;
    const dy = by - ay;
    const lengthSquared = dx * dx + dy * dy;
    const t = lengthSquared === 0 ? 0 : Math.max(0, Math.min(1, -(ax * dx + ay * dy) / lengthSquared));
    nearest = Math.min(nearest, Math.hypot(ax + dx * t, ay + dy * t));
  }
  return Number.isFinite(nearest) ? nearest : Infinity;
}

/**
 * Determines whether a coordinate is within Tacurong City or within an allowed edge buffer (default 100m = 0.1km).
 */
export function isWithinTacurong(lat: number, lng: number, bufferKm: number = 0.1): boolean {
  const y = Number(lat);
  const x = Number(lng);
  if (!Number.isFinite(y) || !Number.isFinite(x)) return false;

  // Fast envelope pre-check (0.05 degrees ~ 5.5 km buffer)
  if (
    y < SERVICE_AREA_BOUNDS.south - 0.05 ||
    y > SERVICE_AREA_BOUNDS.north + 0.05 ||
    x < SERVICE_AREA_BOUNDS.west - 0.05 ||
    x > SERVICE_AREA_BOUNDS.east + 0.05
  ) {
    return false;
  }
  if (isPointInPolygon(y, x, TACURONG_POLYGON_COORDINATES)) return true;
  return distanceOutsideTacurongKm(y, x) <= bufferKm;
}

/**
 * Single source service area gate for web components.
 */
export function isWithinServiceArea(lat: number, lng: number): boolean {
  return isWithinTacurong(lat, lng, 0.1);
}
